"""POS Manager approval PIN.

Why not the standard POS PIN: Odoo stores ``hr.employee.pin`` in clear text and sends every
employee's PIN to each POS device as an unsalted SHA-1 hash, checked in the browser
(pos_hr ``get_barcodes_and_pin_hashed``). A short numeric PIN is recovered from that hash at once,
so typing it proves nothing on the server. The approval PIN is therefore a separate secret:

* stored only as a salted PBKDF2 hash, readable by nobody but the system, never loaded in the POS;
* verified on the server only, among the POS Manager employees of that very point of sale
  (same role rules as pos_hr), with a lockout after repeated failures;
* never equal to any POS login PIN of the company (those are exposed on the devices), and unique
  among the approval PINs of the company (the PIN alone identifies the manager).
"""
import secrets

from passlib.context import CryptContext

from odoo import api, fields, models
from odoo.exceptions import AccessError, UserError

from .urp_tools import urp_lock_rows

URP_PIN_CTX = CryptContext(["pbkdf2_sha512"], pbkdf2_sha512__default_rounds=25000)
PIN_MIN, PIN_MAX = 6, 8


class HrEmployee(models.Model):
    _inherit = "hr.employee"

    urp_approval_pin_hash = fields.Char(copy=False, groups="base.group_system")
    urp_has_approval_pin = fields.Boolean("Return Approval PIN set", compute="_compute_urp_has_approval_pin")

    def _compute_urp_has_approval_pin(self):
        for emp in self:
            emp.urp_has_approval_pin = bool(emp.sudo().urp_approval_pin_hash)

    def _urp_check_approval_pin(self, pin):
        """True when ``pin`` is this employee's approval PIN (constant-time PBKDF2 check)."""
        self.ensure_one()
        stored = self.sudo().urp_approval_pin_hash
        if not stored or not pin:
            return False
        try:
            return URP_PIN_CTX.verify(pin, stored)
        except (ValueError, TypeError):
            return False


class PosConfig(models.Model):
    _inherit = "pos.config"

    def _urp_manager_employees(self):
        """Employees with the POS Manager role on this point of sale, with pos_hr's own rules:
        employees usable on it (company, role lists, current user's employee) whose user is a POS
        Administrator or who are listed as managers. Server data only, never the browser's."""
        self.ensure_one()
        if not self.module_pos_hr:
            return self.env["hr.employee"]
        employees = self.env["hr.employee"].sudo().search(self._employee_domain(self.current_user_id.id))
        group = self.group_pos_manager_id
        return employees.filtered(lambda e: e.active and e.company_id == self.company_id and (
            e in self.manager_employee_ids or (e.user_id and group in e.user_id.all_group_ids)))

    def _urp_login_pins(self):
        """POS login PINs of the employees this POS loads: exposed on the devices."""
        self.ensure_one()
        employees = self.env["hr.employee"].sudo().search(self._employee_domain(self.current_user_id.id))
        return set(employees.mapped("pin")) - {False, ""}

    def _urp_identify_manager(self, pin):
        """The single POS Manager employee of this POS whose approval PIN is ``pin``, or an error code."""
        self.ensure_one()
        if not self.module_pos_hr:
            return None, "pin_unavailable"
        if not pin or not isinstance(pin, str) or not pin.isdigit() or not PIN_MIN <= len(pin) <= PIN_MAX:
            return None, "invalid_pin"
        if pin in self._urp_login_pins():
            return None, "invalid_pin"          # a login PIN is known to the POS devices: never an approval
        found = self._urp_manager_employees().filtered(lambda e: e._urp_check_approval_pin(pin))
        if len(found) != 1:
            return None, "invalid_pin" if not found else "ambiguous_pin"
        return found, None


class UrpApprovalPinWizard(models.TransientModel):
    """The approval PIN is generated by the server, never typed. A PIN chosen by the administrator
    would have to be checked for uniqueness, and that check would tell whether a guessed number is
    another manager's PIN. The form has no PIN field:
    a ``pin`` sent through RPC is refused like any unknown field, whatever its value. The new PIN
    is shown once, after it is saved, and is never stored in clear (not even in this record)."""
    _name = "urp.approval.pin.wizard"
    _description = "Issue a Return Approval PIN"

    employee_id = fields.Many2one("hr.employee", string="Employee", required=True,
                                  domain="[('company_id', 'in', allowed_company_ids)]")
    has_pin = fields.Boolean(related="employee_id.urp_has_approval_pin")

    @api.model_create_multi
    def create(self, vals_list):
        recs = super().create(vals_list)
        for rec in recs:
            rec._urp_check_rights()
        return recs

    def _urp_check_rights(self):
        if not self.env.user.has_group("point_of_sale.group_pos_manager"):
            raise AccessError(self.env._("Only a POS Administrator can set return approval PINs."))
        if self.employee_id.company_id not in self.env.companies:
            raise AccessError(self.env._("You cannot set the approval PIN of an employee of another company."))

    def _urp_generate_pin(self, emp):
        """A random PIN of PIN_MAX digits that is no POS login PIN of the company (those are known to
        the POS devices) and no other employee's approval PIN (the PIN alone identifies the manager).
        A rejected candidate is only ever seen here: nothing about it reaches the user."""
        company_employees = self.env["hr.employee"].sudo().with_context(active_test=False).search(
            [("company_id", "=", emp.company_id.id)])
        login_pins = set(company_employees.mapped("pin")) - {False, ""}
        others = (company_employees - emp).filtered("urp_approval_pin_hash")
        for _attempt in range(20):
            pin = "%0*d" % (PIN_MAX, secrets.randbelow(10 ** PIN_MAX))
            if pin not in login_pins and not others.filtered(lambda e: e._urp_check_approval_pin(pin)):
                return pin
        raise UserError(self.env._("No approval PIN could be issued. Please try again."))

    def action_set(self):
        self.ensure_one()
        self._urp_check_rights()
        emp = self.employee_id.sudo()
        # two PINs issued at the same moment in one company are serialised (the second one is
        # retried with the first one's hash visible), so they can never be equal
        urp_lock_rows(self.env.cr, "res_company", emp.company_id.ids)
        reissued = bool(emp.urp_approval_pin_hash)
        pin = self._urp_generate_pin(emp)
        emp.urp_approval_pin_hash = URP_PIN_CTX.hash(pin)          # the previous PIN stops working
        emp.message_post(body=self.env._("Return approval PIN of %(emp)s %(what)s by %(user)s.", emp=emp.name,
                                         what=self.env._("re-issued (previous PIN revoked)") if reissued
                                         else self.env._("issued"), user=self.env.user.name))
        # shown once, after the PIN is saved; the response is the only place it ever appears
        return {"type": "ir.actions.client", "tag": "display_notification", "params": {
            "title": self.env._("Return approval PIN of %s", emp.name),
            "message": self.env._("New approval PIN: %s. Give it to the employee in person: it will not be shown again.",
                                  pin),
            "type": "warning", "sticky": True, "next": {"type": "ir.actions.act_window_close"}}}

    def action_clear(self):
        self.ensure_one()
        self._urp_check_rights()
        emp = self.employee_id.sudo()
        emp.urp_approval_pin_hash = False
        emp.message_post(body=self.env._("Return approval PIN removed by %s.", self.env.user.name))
        return {"type": "ir.actions.act_window_close"}


class UrpExceptionPinWizard(models.TransientModel):
    """Approval of a POS ship-later request by a POS Manager employee. The PIN typed is checked
    when the form is saved and never written to the database; a wrong PIN is recorded (lockout)
    and shown in the dialog without undoing that record."""
    _name = "urp.exception.pin.wizard"
    _description = "Approve a POS Return Exception with the approval PIN"

    exception_id = fields.Many2one("urp.return.exception", required=True, readonly=True)
    pin = fields.Char("POS Manager Approval PIN", store=False)
    verified = fields.Boolean(readonly=True)
    error = fields.Char(readonly=True)

    def _urp_try(self, pin):
        for rec in self:
            error = rec.exception_id._urp_approve_with_pin(pin)
            models.TransientModel.write(rec, {"verified": not error, "error": error or False})

    @api.model_create_multi
    def create(self, vals_list):
        pins = [vals.pop("pin", False) for vals in vals_list]
        recs = super().create(vals_list)
        for rec, pin in zip(recs, pins):
            if pin:
                rec._urp_try(pin)
        return recs

    def write(self, vals):
        pin = vals.pop("pin", False)
        res = super().write(vals)
        if pin:
            self._urp_try(pin)
        return res

    def action_approve(self):
        self.ensure_one()
        if self.verified:
            return {"type": "ir.actions.act_window_close"}
        if not self.error:
            models.TransientModel.write(self, {"error": self.env._("Enter the approval PIN.")})
        return {"type": "ir.actions.act_window", "res_model": self._name, "res_id": self.id, "view_mode": "form",
                "target": "new", "name": self.env._("POS Manager approval")}
